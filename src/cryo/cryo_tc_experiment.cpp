template <int N>
amrex::Real eval_piecewise_cubic(amrex::Real t,
                                 double const (&xs)[N + 1],
                                 double const (&c)[4][N])
{
    int idx = 0;
    for (int i = 0; i < N; ++i)
    {
        if (t >= xs[i] && t < xs[i + 1])
        {
            idx = i;
            break;
        }
        if (t >= xs[N])
        {
            idx = N - 1;
        }
    }

    double const dt = t - xs[idx];
    return static_cast<amrex::Real>(((c[0][idx] * dt + c[1][idx]) * dt + c[2][idx]) * dt + c[3][idx]);
}

